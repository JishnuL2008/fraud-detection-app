"""Machine-learning layer: a Gradient Boosting classifier trained at startup.

The model learns from synthetic labelled transactions generated by the simulator
(normal vs. fraud-like). It is a demo model: in production you would train on
real, labelled transaction history.
"""
import itertools
import random

import numpy as np
from sklearn.ensemble import GradientBoostingClassifier

import simulator
from simulator import USERS, normal_txn

FEATURE_NAMES = ["amount_ratio", "odd_hour", "new_payee", "away_from_home", "recent_transfers"]

_model = None


def features(txn, recent_count=1):
    """Turn a transaction into a numeric feature row."""
    info = USERS[txn["user"]]
    return [
        txn["amount"] / info["avg"],
        1 if 0 <= txn["hour"] <= 5 else 0,
        1 if txn["new_payee"] else 0,
        1 if txn["location"] != info["home"] else 0,
        recent_count,
    ]


def _fraud_sample(rng):
    """One synthetic fraud case, drawn from three different fraud patterns."""
    user = rng.choice(list(USERS))
    info = USERS[user]
    pattern = rng.choice(["takeover", "burst", "scam"])
    txn = {
        "id": 0, "user": user, "payee": "x", "new_payee": True,
        "amount": int(info["avg"] * rng.uniform(5, 12)),
        "hour": rng.choice([0, 1, 2, 3, 4, 5]),
        "location": rng.choice([info["home"], "Delhi", "Kolkata"]),
    }
    recent = rng.choice([1, 1, 2])
    if pattern == "burst":      # many quick transfers to new payees, any time of day
        txn["amount"] = int(info["avg"] * rng.uniform(3, 8))
        txn["hour"] = rng.randint(6, 23)
        txn["location"] = info["home"]
        recent = rng.randint(3, 6)
    elif pattern == "scam":     # victim tricked into a large payment, daytime
        txn["amount"] = int(info["avg"] * rng.uniform(5, 15))
        txn["hour"] = rng.randint(8, 21)
        txn["location"] = info["home"]
    return features(txn, recent)


def _training_data(n_normal=3000, n_fraud=900):
    rng = random.Random(42)
    random.seed(42)  # simulator uses the global RNG
    X, y = [], []
    for _ in range(n_normal):
        X.append(features(normal_txn(), recent_count=rng.choice([1, 1, 1, 2])))
        y.append(0)
    for _ in range(n_fraud):
        X.append(_fraud_sample(rng))
        y.append(1)
    random.seed()  # restore randomness for the live stream
    # Training consumed simulator IDs; reset so the live stream starts at #1.
    simulator._ids = itertools.count(1)
    simulator._payee_ids = itertools.count(1)
    return np.array(X), np.array(y)


def train():
    global _model
    X, y = _training_data()
    _model = GradientBoostingClassifier(n_estimators=80, max_depth=3, random_state=42)
    _model.fit(X, y)
    return _model


def fraud_probability(txn, recent_count=1):
    """Return the model's fraud probability (0.0 - 1.0) for one transaction."""
    if _model is None:
        train()
    return float(_model.predict_proba([features(txn, recent_count)])[0][1])


def top_factors(k=2):
    """Global feature importance, as readable text for the UI."""
    if _model is None:
        train()
    order = np.argsort(_model.feature_importances_)[::-1][:k]
    return [FEATURE_NAMES[i] for i in order]


if __name__ == "__main__":
    train()
    print("Most important features:", top_factors(3))
